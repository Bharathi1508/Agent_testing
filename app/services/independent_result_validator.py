import hashlib
import json
import uuid
from datetime import datetime, timezone
from pathlib import Path


class IndependentResultValidator:

    def __init__(self, output_dir=None):
        self.output_dir = Path(
            output_dir or "reports/phase22_20/validation"
        )

    @staticmethod
    def _fingerprint(payload):
        canonical = json.dumps(
            payload,
            sort_keys=True,
            separators=(",", ":"),
            default=str,
        )
        return hashlib.sha256(
            canonical.encode("utf-8")
        ).hexdigest()

    def validate_metadata(self, evidence, reference):
        findings = []

        # Verify the evidence fingerprint generated
        # by the Step 3 evidence collector.
        evidence_body = {
            key: value
            for key, value in evidence.items()
            if key != "fingerprint"
        }

        fingerprint_valid = (
            self._fingerprint(evidence_body)
            == evidence.get("fingerprint")
        )

        if not fingerprint_valid:
            findings.append({
                "category": "evidence_integrity",
                "severity": "high",
                "message": "Evidence fingerprint mismatch",
            })

        # Validate the trusted reference fingerprint
        # generated by the Step 2 builder.
        reference_body = {
            "catalog": reference.get("catalog"),
            "schema": reference.get("schema"),
            "table": reference.get("table"),
            "columns": reference.get("columns"),
        }

        reference_valid = (
            self._fingerprint(reference_body)
            == reference.get("fingerprint")
        )

        if not reference_valid:
            findings.append({
                "category": "reference_integrity",
                "severity": "high",
                "message": "Trusted reference fingerprint mismatch",
            })

        if not fingerprint_valid or not reference_valid:
            status = "inconclusive"
        elif evidence.get("source_type") != "real_agent":
            status = "inconclusive"
            findings.append({
                "category": "execution_provenance",
                "severity": "medium",
                "message": (
                    "Evidence is not identified as "
                    "real agent execution"
                ),
            })
        elif not evidence.get(
            "provenance_verified_by_collector", False
        ):
            status = "inconclusive"
            findings.append({
                "category": "execution_provenance",
                "severity": "medium",
                "message": (
                    "Execution provenance has not "
                    "been independently verified"
                ),
            })
        elif evidence.get("execution_status") != "completed":
            status = "inconclusive"
            findings.append({
                "category": "execution_status",
                "severity": "medium",
                "message": "Agent execution did not complete",
            })
        else:
            status = "pass"

        response = evidence.get("response")
        columns = reference.get("columns")

        if not isinstance(response, dict):
            findings.append({
                "category": "invalid_response",
                "severity": "high",
                "message": "Agent response must be an object",
            })
            if status == "pass":
                status = "fail"

        elif not isinstance(columns, list):
            findings.append({
                "category": "invalid_reference",
                "severity": "high",
                "message": "Reference columns must be a list",
            })
            status = "inconclusive"

        else:
            actual_table = response.get("table")
            expected_table = reference.get("table")

            if actual_table != expected_table:
                findings.append({
                    "category": "incorrect_table",
                    "severity": "high",
                    "expected": expected_table,
                    "actual": actual_table,
                })
                if status == "pass":
                    status = "fail"

            expected_columns = {
                item["column_name"]: item["data_type"]
                for item in columns
            }

            returned_columns = response.get("columns")

            if not isinstance(returned_columns, list):
                findings.append({
                    "category": "invalid_columns",
                    "severity": "high",
                    "message": (
                        "Response columns must be a list"
                    ),
                })
                if status == "pass":
                    status = "fail"
            else:
                for item in returned_columns:
                    if isinstance(item, str):
                        name = item
                        returned_type = None
                    elif isinstance(item, dict):
                        name = item.get("column_name")
                        returned_type = item.get("data_type")
                    else:
                        name = None
                        returned_type = None

                    if name not in expected_columns:
                        findings.append({
                            "category": "unknown_column",
                            "severity": "high",
                            "column": name,
                            "message": (
                                "Column does not exist "
                                "in trusted reference"
                            ),
                        })
                        if status == "pass":
                            status = "fail"

                    elif (
                        returned_type is not None
                        and returned_type.upper()
                        != expected_columns[name].upper()
                    ):
                        findings.append({
                            "category": "incorrect_data_type",
                            "severity": "medium",
                            "column": name,
                            "expected": expected_columns[name],
                            "actual": returned_type,
                        })
                        if status == "pass":
                            status = "fail"

        return {
            "validation_id": str(uuid.uuid4()),
            "phase": "22.20",
            "validated_at": datetime.now(
                timezone.utc
            ).isoformat(),
            "agent_id": evidence.get("agent_id"),
            "test_id": evidence.get("test_id"),
            "evidence_id": evidence.get("evidence_id"),
            "reference_fingerprint": reference.get(
                "fingerprint"
            ),
            "status": status,
            "findings": findings,
            "finding_count": len(findings),
            "checks": {
                "evidence_fingerprint_valid": fingerprint_valid,
                "reference_fingerprint_valid": reference_valid,
            },
        }

    def save_report(self, report):
        self.output_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        validation_id = report["validation_id"]
        uuid.UUID(validation_id)

        path = self.output_dir / (
            f"validation_{validation_id}.json"
        )

        with path.open(
            "x", encoding="utf-8"
        ) as file:
            json.dump(report, file, indent=2)

        return str(path)
